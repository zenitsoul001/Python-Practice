# Class ek blueprint hota hai
# Matlab ek structure jiske according objects banaye jaate hain


class Student:

    # Class ke andar variables ko attributes bolte hain

    name = "Gagan"
    age = 22
    course = "Python"


# Object create karna
# Object class ka real example hota hai

student1 = Student()


# Object ke through attributes access karna

print(student1.name)
print(student1.age)
print(student1.course)



# Ek aur object

student2 = Student()

print(student2.name)